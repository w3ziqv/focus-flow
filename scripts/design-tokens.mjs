import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../src/design/tokens.json', import.meta.url)
const target = new URL('../src/design/tokens.css', import.meta.url)
const { foundation, themes } = JSON.parse(readFileSync(source, 'utf8'))
const declarations = values => Object.entries(values).map(([key, value]) => `  --${key}: ${value};`).join('\n')
const css = `/* Generated by scripts/design-tokens.mjs from tokens.json. */\n@theme {\n${declarations({ ...themes.light, ...foundation })}\n}\n${Object.entries(themes).filter(([name]) => name !== 'light').map(([name, values]) => `\n.${name} {\n${declarations(values)}\n}\n`).join('')}`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) throw Error('Design tokens are stale. Run npm run design:tokens.')
  console.log('PASS: generated CSS matches the single token source')
} else writeFileSync(target, css)
